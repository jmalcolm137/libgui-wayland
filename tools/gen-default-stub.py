#!/usr/bin/env python3
"""Generate a concrete default implementation of a SerenityOS IPC endpoint Stub.

The IPC compiler emits `<Name>Stub` with all-pure-virtual methods. LibWM only
implements the subset an application uses; this generator produces a base class
that satisfies the rest with harmless defaults, so LibWM can override just what
it cares about.

Non-void (synchronous) methods return a *valid* response built from
default-constructed values (false, 0, empty strings, containers and bitmaps).
They must not return the invalid `ResponseType(nullptr)`: `Stub::handle()`
turns that into an error, LibIPC then sends no reply at all, and the client's
`send_sync()` waits forever.

Usage:
    gen-default-stub.py HEADER OUTPUT [--base WindowServer] [--extra-include ...]
"""
import re
import sys
from collections import Counter


def split_top_level(params: str) -> list[str]:
    parts, depth, current = [], 0, ""
    for ch in params:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(current.strip())
            current = ""
        else:
            current += ch
    if current.strip():
        parts.append(current.strip())
    return parts


def default_response(text: str, return_type: str) -> str:
    """`ReturnType(T1 {}, T2 {}, ...)` from the response class's value constructor."""
    short = return_type.split("::")[-1]
    start = text.index(f"class {short} final")
    end = text.index("\n};", start)
    body = text[start:end]
    ctor = re.compile(rf"^\s*{short}\(([^)]*)\)\s*(?::|\{{)", re.MULTILINE)
    for match in ctor.finditer(body):
        params = match.group(1).strip()
        if params.startswith("decltype(nullptr)") or params.startswith(short):
            continue
        types = [p.rsplit(" ", 1)[0] for p in split_top_level(params)]
        args = ", ".join(f"{t} {{}}" for t in types)
        return f"{return_type}({args})"
    raise ValueError(f"no value constructor for {short}")


def main() -> int:
    positional = []
    base = "WindowServer"
    include_dir = None
    extra_includes = []
    namespace = "LibWM"
    args = sys.argv[1:]
    i = 0
    while i < len(args):
        if args[i] == "--base":
            base = args[i + 1]
            i += 2
        elif args[i] == "--include-dir":
            include_dir = args[i + 1]
            i += 2
        elif args[i] == "--namespace":
            namespace = args[i + 1]
            i += 2
        elif args[i] == "--extra-include":
            extra_includes.append(args[i + 1])
            i += 2
        else:
            positional.append(args[i])
            i += 1

    if include_dir is None:
        include_dir = base

    if len(positional) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    header, out = positional[0], positional[1]
    stub_class = f"{base}Stub"
    endpoint = f"{base}Endpoint"
    default_stub = f"{base}DefaultStub"

    text = open(header).read()
    start = text.index(f"class {stub_class} : public IPC::Stub {{")
    end = text.index("\n};", start)
    body = text[start:end]

    # Skip the concrete magic()/name()/handle() overrides by brace-matching the
    # handle() body, leaving only the pure-virtual section.
    handle_at = body.index("handle(")
    brace = body.index("{", handle_at)
    depth = 0
    i = brace
    while i < len(body):
        if body[i] == "{":
            depth += 1
        elif body[i] == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    body = body[i + 1 :]

    pattern = re.compile(
        r"virtual\s+(.+?)\s+([A-Za-z_]\w*)\s*\((.*?)\)\s*(const)?\s*=\s*0;",
        re.DOTALL,
    )
    methods = []
    for ret, name, args, const in pattern.findall(body):
        ret = ret.strip()
        args = re.sub(r"\s+", " ", args).strip()
        if any(tok in ret for tok in (" ", "\n", "~")) or any(
            tok in args for tok in ("override", "{", "}", "return")
        ):
            continue
        methods.append((ret, name, args, bool(const)))

    if not methods:
        print(f"ERROR: no pure-virtual methods parsed from {header}", file=sys.stderr)
        return 1

    print(f"{base}: {len(methods)} methods; return types: {dict(Counter(m[0] for m in methods))}")

    lines = []
    lines.append("// GENERATED by tools/gen-default-stub.py. Do not edit by hand.")
    lines.append("#pragma once")
    lines.append("")
    for extra in extra_includes:
        lines.append(f"#include <{extra}>")
    lines.append(f"#include <{include_dir}/{endpoint}.h>")
    lines.append("")
    lines.append(f"namespace {namespace} {{")
    lines.append("")
    lines.append(f"// Harmless defaults for every {endpoint}::Stub method.")
    lines.append(f"class {default_stub} : public {endpoint}::Stub {{")
    lines.append("public:")
    lines.append(f"    virtual ~{default_stub}() = default;")
    lines.append("")
    for ret, name, args, const in methods:
        qualifier = " const" if const else ""
        if ret == "void":
            lines.append(f"    virtual void {name}({args}){qualifier} override {{ }}")
        else:
            lines.append(f"    virtual {ret} {name}({args}){qualifier} override {{ return {default_response(text, ret)}; }}")
    lines.append("};")
    lines.append("")
    lines.append(f"}} // namespace {namespace}")
    lines.append("")

    with open(out, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {out} ({len(methods)} methods)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
